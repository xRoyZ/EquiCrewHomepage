"""Development server for the static EquiCrew website (standard library only).

Serves the files of this directory exactly as a static host would: a directory
answers with its index.html, everything else that does not exist is a real 404
(no directory listing, no fallback page). The one generated file is
/js/config.js, which carries the API base URL from the environment variable
API_BASE_URL so the contact form reaches the API wherever it runs.

Usage:
    python3 dev_server.py [PORT]
    python3 dev_server.py --port 8080 --host 127.0.0.1
The port comes from the argument, else from PORT, else 8080.
"""

from __future__ import annotations

import argparse
import io
import json
import os
import sys
import urllib.parse
from functools import partial
from http import HTTPStatus
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import BinaryIO

SITE_DIR = Path(__file__).resolve().parent
DEFAULT_PORT = 8080
CONFIG_PATH = "/js/config.js"

# Files of the development tooling that are no part of the website.
HIDDEN_TOP_LEVEL = {"tests", "node_modules", "dev_server.py", "package.json", "package-lock.json"}

# Content types the site relies on, independent of the host's mimetypes table.
CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".woff2": "font/woff2",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".txt": "text/plain; charset=utf-8",
}


def api_base_from_env() -> str:
    """The API origin from API_BASE_URL, without a trailing slash ("" = same origin).

    A value that is still an unresolved RUN.json placeholder (the api service is
    not declared on this branch) counts as unset.
    """
    value = os.environ.get("API_BASE_URL", "").strip().rstrip("/")
    if "${" in value:
        return ""
    return value


def config_module(api_base: str) -> bytes:
    """The body of /js/config.js for the given API base."""
    return (
        "// Generated by dev_server.py from API_BASE_URL.\n"
        f"export const API_BASE = {json.dumps(api_base)};\n"
    ).encode()


def is_hidden(url_path: str) -> bool:
    """True for paths that belong to the tooling, not to the website."""
    parts = [p for p in url_path.split("/") if p]
    if not parts:
        return False
    if any(p.startswith(".") for p in parts):
        return True
    return parts[0] in HIDDEN_TOP_LEVEL


class SiteHandler(SimpleHTTPRequestHandler):
    """Static file handler with real 404s and a generated config module."""

    def guess_type(self, path: str | os.PathLike[str]) -> str:
        ext = os.path.splitext(os.fspath(path))[1].lower()
        return CONTENT_TYPES.get(ext) or super().guess_type(path)

    def end_headers(self) -> None:
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()

    def send_head(self) -> BinaryIO | None:
        path = urllib.parse.unquote(urllib.parse.urlsplit(self.path).path)
        if path == CONFIG_PATH:
            body = config_module(api_base_from_env())
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", "text/javascript; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            return io.BytesIO(body)
        if is_hidden(path):
            self.send_error(HTTPStatus.NOT_FOUND, "Seite nicht gefunden")
            return None
        return super().send_head()

    def list_directory(self, path: str | os.PathLike[str]) -> BinaryIO | None:
        # A directory without index.html is not a page: no listing, a real 404.
        self.send_error(HTTPStatus.NOT_FOUND, "Seite nicht gefunden")
        return None


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Serve the EquiCrew website for development.")
    parser.add_argument("port_arg", nargs="?", type=int, help="port to listen on")
    parser.add_argument("--port", type=int, help="port to listen on")
    parser.add_argument("--host", default="127.0.0.1", help="interface to bind")
    return parser.parse_args(argv)


def resolve_port(args: argparse.Namespace) -> int:
    if args.port is not None:
        return args.port
    if args.port_arg is not None:
        return args.port_arg
    raw = os.environ.get("PORT", "").strip()
    if not raw:
        return DEFAULT_PORT
    try:
        return int(raw)
    except ValueError:
        sys.exit(f"PORT must be a number, got {raw!r}")


def main(argv: list[str] | None = None) -> None:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    port = resolve_port(args)
    try:
        server = ThreadingHTTPServer(
            (args.host, port), partial(SiteHandler, directory=str(SITE_DIR))
        )
    except OSError as exc:
        sys.exit(f"Cannot listen on {args.host}:{port}: {exc.strerror or exc}")
    api_base = api_base_from_env() or "(same origin)"
    # The bound port, so "--port 0" (a free port, used by the tests) is reported truly.
    bound_port = server.server_address[1]
    print(f"EquiCrew website on http://{args.host}:{bound_port}/ - API base {api_base}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
